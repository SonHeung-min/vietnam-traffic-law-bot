def make_so_hieu_slug(so_hieu: str) -> str:
    """
    Chuyển số hiệu thành slug dùng cho chunk_id.
    '168/2024/NĐ-CP' → '168-2024-ND-CP'
    '36/2024/QH15'    → '36-2024-QH15'
    """
    return (
        so_hieu
        .replace("/", "-")
        .replace("NĐ", "ND")
    )
